
# 运算符优先级
# () 括号，优先级最高
# + - 优先级 低于 * / // %    ** (幂运算优先级高)
n = 4 + 3 * 2 ** 3
print(n)


# 比较运算符
#  > < >= <= == !=  (优先级低于运算符)
n = 4 + 5 > 3 + 4
print(n)    # True


# 逻辑运算符
# and or not  (优先级低于比较运算符)
n = 4 + 5 > 3 + 4 and 6 < 7     # 相当于：(4 + 5 > 3 + 4) and 6 < 7
print(n)


