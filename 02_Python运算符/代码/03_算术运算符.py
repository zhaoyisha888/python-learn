

# Python算术运算符：
#    +  -  *  /（除不尽得到小数）  %（取余数）  //（整除:向下取整——比我小的最大整数）   **（次方，取幂）
print(10 + 4)   # 14
print(10 - 4)   # 6
print(10 * 4)   # 40
print(10 / 4)   # 2.5
print(10 % 4)   # 取余数，2
print(10 // 4)  # 向下取整，保留整数，2
print(10 ** 4)  # 10000
print(10 ** 0.5)  # 开根号，结果为10的0.5次方，即10的平方根，结果为3.1622776601683795

print(-10 / 4)  # -2.5
print(-10 // 4)  # -3  向下取整，比我小的最大整数，-3
print(10 // -4)  # -3  向下取整，比我小的最大整数，-3
print(-10 // -4)  # 2  向下取整，比我小的最大整数，2


# 科学计数法
a = 3.14 * 10 ** 3  
b = 3.14e3
print(a,b)  #  3.14 * 1000 = 3140.0
a = 3.14 * 10 ** -3  
b = 3.14e-3
print(a,b)  # 3.14 * 0.001 = 0.00314


