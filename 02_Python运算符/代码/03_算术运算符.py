# Q：从控制台输入一个三位数，输出它的个位、十位、百位
num = int(input("请输入一个三位数："))
# 取个位： num % 10
print("个位：{}".format(num % 10))
# 取十位： num // 10 % 10
print("十位：{}".format(num // 10 % 10)) 
# 取百位： num // 100 % 10
print("百位：{}".format(num // 100 % 10))

